# frozen_string_literal: true
require "digest"
require "json"
require "pathname"
module Hamster
  module Build
    module Assets
      module_function
      MIME = {".js" => "text/javascript", ".css" => "text/css", ".svg" => "image/svg+xml", ".png" => "image/png", ".jpg" => "image/jpeg", ".woff2" => "font/woff2", ".txt" => "text/plain"}.freeze
      def outputs(root)
        %w[app app/assets].each { |path| raise ArgumentError, "Symlink asset root: #{path}" if File.symlink?(File.join(root, path)) }
        sources = {}
        Dir.glob("app/assets/**/*", File::FNM_DOTMATCH, base: root).sort.each do |path|
          raise ArgumentError, "Symlink asset path: #{path}" if File.symlink?(File.join(root, path))
          next unless File.file?(File.join(root, path)) && MIME.key?(File.extname(path))
          sources[path.delete_prefix("app/assets/")] = File.binread(File.join(root, path))
        end
        if sources.key?("vendor/stimulus.js")
          controllers = sources.keys.grep(%r{\Acontrollers/.*_controller\.js\z}).sort
          generated = ["import { Application } from './vendor/stimulus.js';", "const application = Application.start();"]
          controllers.each_with_index do |path, index|
            name = path.delete_prefix("controllers/").delete_suffix("_controller.js").tr("_", "-").gsub("/", "--")
            generated << "import Controller#{index} from './#{path}';"
            generated << "application.register(#{name.to_json}, Controller#{index});"
          end
          raise ArgumentError, "controllers.js is generated; customize application.js instead" if sources.key?("controllers.js")
          sources["controllers.js"] = generated.join("\n") + "\n"
        end
        mapping, artifacts = {}, {}
        compile = nil
        compile = lambda do |name, stack|
          return mapping[name] if mapping.key?(name)
          raise ArgumentError, "Missing asset #{name}" unless sources.key?(name)
          raise ArgumentError, "Cyclic asset imports: #{(stack + [name]).join(' -> ')}" if stack.include?(name)
          bytes = sources[name]
          if %w[.js .css].include?(File.extname(name))
            text = bytes.dup.force_encoding("UTF-8")
            raise ArgumentError, "Invalid UTF-8 asset #{name}" unless text.valid_encoding?
            # Only relative ESM references are rewritten. Vendored bundles are
            # self-contained; application modules use explicit relative imports.
            pattern = File.extname(name) == ".js" ? /((?:\bfrom\s*|\bimport\s*\(?\s*)["'])(\.{1,2}\/[^"']+)(["'])/ : /(url\(\s*["']?)(\.{0,2}\/?[^)'"\s]+)(["']?\s*\))/
            text = text.gsub(pattern) do
              prefix, reference, suffix = Regexp.last_match.captures
              if reference.start_with?("data:", "http:", "https:", "/", "#")
                "#{prefix}#{reference}#{suffix}"
              else
                target = Pathname.new(File.join(File.dirname(name), reference)).cleanpath.to_s
                raise ArgumentError, "Asset import escapes root: #{name}" if target.start_with?("../")
                fingerprint = compile.call(target, stack + [name])
                # Absolute fingerprint URLs make imports independent of nesting.
                "#{prefix}/assets/#{fingerprint}#{suffix}"
              end
            end
            bytes = text
          end
          digest = Digest::SHA256.hexdigest(bytes)[0, 32]
          extension = File.extname(name)
          fingerprint = name.delete_suffix(extension) + "-#{digest}" + extension
          mapping[name] = fingerprint
          artifacts["public/assets/#{fingerprint}"] = bytes
          fingerprint
        end
        sources.keys.sort.each { |name| compile.call(name, []) }
        map = mapping.keys.sort.to_h { |key| [key, "/assets/#{mapping[key]}"] }
        entries = mapping.to_h { |name, file| ["/assets/#{file}", MIME.fetch(File.extname(name))] }
        artifacts["public/assets/manifest.json"] = JSON.pretty_generate({"format_version" => 1, "assets" => map}) + "\n"
        artifacts["config/asset_registry.rb"] = "# Generated by hamster manifest.\nmodule Hamster\n  module CompiledAssets\n    def self.paths; #{map.inspect}; end\n    def self.types; #{entries.sort.to_h.inspect}; end\n  end\nend\n"
        artifacts
      end
    end
  end
end
