# frozen_string_literal: true
require "ripper"
require_relative "callbacks"
module Hamster
  module Build
    module Jobs
      module_function
      def literal(node)
        return node[1][1][1] if node && node[0] == :string_literal && node[1].length == 2 && node[1][1][0] == :@tstring_content
        return node[1].to_i if node && node[0] == :@int
        if node && node[0] == :array
          return (node[1] || []).map { |n| literal(n) }
        end
        raise ArgumentError, "Job names and versions must be literal"
      end
      def declarations(node, owner = "", result = [])
        return result unless node.is_a?(Array)
        if [:class, :module].include?(node[0])
          local = Callbacks.constant(node[1])
          raise ArgumentError, "dynamic job declaration" unless local
          owner = local.include?("::") ? local : [owner, local].reject(&:empty?).join("::")
          declarations(node[node[0] == :class ? 3 : 2], owner, result)
        elsif [:def, :defs].include?(node[0])
          return result
        elsif node[0] == :method_add_arg && node.dig(1, 0) == :fcall && node.dig(1, 1, 1) == "job"
          arguments = node[2][0] == :arg_paren ? node[2][1] : node[2]
          declarations([:command, node[1][1], arguments], owner, result)
        elsif node[0] == :command && node.dig(1, 1) == "job"
          args = node[2][1]
          name = literal(args.first)
          options = args.find { |arg| arg[0] == :bare_assoc_hash }
          values = options ? options[1].to_h { |pair| [pair[1][1].delete_suffix(":"), literal(pair[2])] } : {}
          version = values.fetch("version", 1)
          accepts = (values.fetch("accepts", []) + [version]).uniq
          raise ArgumentError, "Invalid job name/version" unless name.is_a?(String) && name.match?(/\A[a-z][a-z0-9_.-]*\z/) && accepts.all? { |v| v.is_a?(Integer) && v > 0 }
          result << [owner, name, accepts]
        else
          node.each { |child| declarations(child, owner, result) if child.is_a?(Array) }
        end
        result
      end
      def compile(sources)
        definitions = {}
        sources.each { |source| Callbacks.scan(Ripper.sexp(source), "", definitions) }
        jobs = sources.flat_map { |source| declarations(Ripper.sexp(source)) }.sort_by { |job| job[1] }
        raise ArgumentError, "Duplicate job name" unless jobs.map { |job| job[1] }.uniq.length == jobs.length
        jobs.each do |owner, _, _|
          current, seen = owner, []
          until current == "Hamster::Job"
            raise ArgumentError, "#{owner}: job declaration must inherit Hamster::Job" if seen.include?(current) || !definitions[current]
            seen << current
            parent = definitions[current][:parent]
            scopes = current.split("::")[0...-1]
            current = scopes.length.downto(0).map { |n| (scopes.take(n) + [parent]).compact.join("::") }.find { |name| definitions.key?(name) } || parent
          end
        end
        lines = ["# Generated by hamster manifest.", "module Hamster", "  module CompiledJobs", "    def self.accepts?(name, version)"]
        if jobs.empty?
          lines << "      false"
        else
          lines << "      case name"
          jobs.each { |_, name, versions| lines << "      when #{name.inspect} then #{versions.inspect}.include?(version)" }
          lines += ["      else false", "      end"]
        end
        lines += ["    end", "    def self.execute_registered_job(name, version, arguments)"]
        unless jobs.empty?
          lines << "      case name"
          jobs.each do |owner, name, versions|
            lines += ["      when #{name.inspect}", "        raise Hamster::Jobs::UnknownJob, 'Unsupported job version' unless #{versions.inspect}.include?(version)", "        return #{owner}.new.perform(arguments, version: version)"]
          end
          lines << "      end"
        end
        lines += ["      raise Hamster::Jobs::UnknownJob, 'Unknown job'", "    end", "  end", "end"]
        lines.join("\n") + "\n"
      end
    end
  end
end
