# frozen_string_literal: true

require "ripper"

module Hamster
  module ViewCompiler
    module_function

    NAME = /\A[a-z][a-z0-9_]*(?:\/[a-z][a-z0-9_]*)*\z/
    TAG = /<%(=|#)?(.*?)%>/m
    RENDER = /\Arender\s*(?:\(\s*)?["']([^"']+)["']/m

    def compile(sources)
      names = sources.keys.sort
      paths = {}
      method_names = {}
      names.each do |name|
        raise View::Error, "invalid template name #{name}" unless name.match?(NAME)
        paths[name] = sources[name].fetch(:path)
        method = method_name(name)
        if method_names.key?(method)
          raise View::Error, "#{paths[name]}:1: duplicate generated method for #{name} and #{method_names[method]}"
        end
        method_names[method] = name
      end
      methods = {}
      dependencies = {}
      required = names.to_h { |name| [name, declared_locals(sources[name].fetch(:source), paths[name])] }
      names.each do |name|
        methods[name], dependencies[name] = compile_one(name, sources[name].fetch(:source), paths[name], paths, required)
      end
      detect_cycles!(dependencies, paths)
      out = ["# frozen_string_literal: true", "", "# Generated by bin/hamster manifest. Edit .html.erb files instead.", "module Hamster", "  module CompiledViews", "    module_function"]
      names.each { |name| out.concat(methods.fetch(name)) }
      out.concat(["    def render(name, context, locals)", "      Hamster::View.instrument_compiled(name) { dispatch(name, context, locals) }", "    end", "    def dispatch(name, context, locals)"])
      if names.empty?
        out << "      raise Hamster::View::Error, \"missing template #{'#{name}'}\""
      else
        out << "      case name"
        names.each { |name| out << "      when #{name.dump} then #{method_name(name)}(context, locals)" }
        out.concat(["      else raise Hamster::View::Error, \"missing template #{'#{name}'}\"", "      end"])
      end
      out.concat(["    end", "  end", "end", "", "Hamster::View.use_compiled!"])
      result = out.join("\n")
      raise View::Error, "generated views contain invalid Ruby" unless Ripper.sexp(result)
      result
    end

    def compile_one(name, source, path, paths, required)
      locals = declared_locals(source, path)
      body = []
      deps = []
      blocks = []
      cursor = 0
      source.to_enum(:scan, TAG).each do
        match = Regexp.last_match
        literal = source[cursor...match.begin(0)]
        body << "      output << #{literal.dump}" unless literal.empty?
        line = source[0...match.begin(0)].count("\n") + 1
        tag = match[1]
        code = match[2].strip
        if tag == "#"
          # Comments are removed before the native build.
        elsif tag == "="
          context = View.position(source[0...match.begin(0)].gsub(TAG, ""))
          validate_position!(context, path, line)
          if (partial = partial_name(code, path, line))
            raise View::Error, "#{path}:#{line}: missing template #{partial}" unless paths.key?(partial)
            deps << [partial, line]
            expression = rewrite_render(code, partial, path, line, required.fetch(partial))
          elsif code.match?(/(?:\A|[^.])\brender\b/)
            raise View::Error, "#{path}:#{line}: render requires a literal template name"
          elsif name.start_with?("layouts/") && (slot = yield_name(code, path, line))
            expression = "context.slot(#{slot.dump})"
          elsif code.match?(/\byield\b/)
            raise View::Error, "#{path}:#{line}: yield is only supported in layouts"
          elsif code.match?(/\Acontent_for\b/)
            expression = rewrite_content_for(code, path, line)
          else
            expression = code
          end
          check_ruby!(expression, path, line)
          body << "      Hamster::View.append_value(output, (#{expression}), #{path.dump}, #{line}, #{context.inspect})"
        else
          raise View::Error, "#{path}:#{line}: unsupported ERB code" if code.match?(/\brender\b|\byield\b/)
          if (slot = code.match(/\Acontent_for\s*(?:\(\s*)?:(\w+)\s*(?:\)\s*)?do\s*\z/))
            index = blocks.length
            blocks << [:content_for, slot[1], index, line]
            body << "      previous_output_#{index} = output"
            body << "      output = []"
          elsif code == "end"
            block = blocks.pop
            raise View::Error, "#{path}:#{line}: unexpected end" unless block
            if block.is_a?(Array) && block[0] == :content_for
              body << "      context.content_for(#{block[1].dump}, Hamster::HTML::Fragment.new(output.join))"
              body << "      output = previous_output_#{block[2]}"
            else
              body << "      end"
            end
          else
            check_ruby_fragment!(code, path, line)
            blocks << [:ruby, line] if code.match?(/\A(?:if|unless|for)\b/) || code.match?(/\bdo\s*(?:\|[^|]*\|)?\s*\z/)
            body << "      #{code}"
          end
        end
        cursor = match.end(0)
      end
      tail = source[cursor..-1]
      if tail.include?("<%")
        line = source[0...cursor].count("\n") + tail[0...tail.index("<%")].count("\n") + 1
        raise View::Error, "#{path}:#{line}: unterminated ERB tag"
      end
      body << "      output << #{tail.dump}" unless tail.empty?
      raise View::Error, "#{path}:#{blocks.last[-1]}: unclosed ERB block" unless blocks.empty?
      source_without_comments = source.gsub(/<%#.*?%>/m, "")
      if (undeclared = inferred_locals(source_without_comments) - locals).any?
        raise View::Error, "#{path}:1: undeclared locals: #{undeclared.join(', ')}"
      end
      lines = ["    def #{method_name(name)}(context, locals)", "      output = []"]
      locals.each { |local| lines << "      #{local} = context.fetch(locals, #{path.dump}, #{local.dump}, #{first_use_line(source, local)})" }
      lines.concat(body)
      lines.concat(["      Hamster::HTML::Fragment.new(output.join)", "    end"])
      ruby = lines.join("\n")
      parsed = Ripper.sexp("module X\n#{ruby}\nend")
      unless parsed
        raise View::Error, "#{path}: invalid ERB Ruby syntax"
      end
      if (unknown = unresolved_identifier(parsed))
        raise View::Error, "#{path}:1: undeclared local #{unknown}"
      end
      [lines, deps]
    end

    def declared_locals(source, path = "template")
      declaration = source.match(/\A\s*<%#\s*locals:\s*([^%]*?)\s*%>/m)
      return inferred_locals(source) unless declaration
      names = declaration[1].split(",").map(&:strip)
      raise View::Error, "#{path}:1: invalid locals declaration" unless names.all? { |n| n.match?(/\A[a-z_][a-z0-9_]*\z/) } && names.uniq == names
      names
    end

    def inferred_locals(source)
      source.scan(/<%=\s*([a-z_][a-z0-9_]*)\s*%>/).flatten.uniq.sort - %w[yield]
    end

    def first_use_line(source, local)
      source.to_enum(:scan, TAG).each do
        match = Regexp.last_match
        next if match[1] == "#"
        return source[0...match.begin(0)].count("\n") + 1 if match[2].match?(/\b#{Regexp.escape(local)}\b/)
      end
      1
    end

    def method_name(name)
      "view_#{name.tr('/', '_')}"
    end

    def partial_name(code, path, line)
      return nil unless code.match?(/\Arender\b/)
      match = code.match(RENDER)
      raise View::Error, "#{path}:#{line}: render requires a literal template name" unless match
      match[1]
    end

    def rewrite_render(code, name, path, line, required)
      rest = code.sub(RENDER, "")
      rest = rest.sub(/\A\s*,\s*locals:\s*/, "")
      rest = rest.sub(/\A\s*locals:\s*/, "")
      rest = rest.sub(/\)\s*\z/, "").strip
      locals = rest.empty? ? "{}" : rest
      unless locals.start_with?("{") && locals.end_with?("}") && Ripper.sexp(locals)
        raise View::Error, "#{path}:#{line}: render requires locals: { ... }"
      end
      keys = locals.scan(/\b([a-z_][a-z0-9_]*):/).flatten
      missing = required - keys
      raise View::Error, "#{path}:#{line}: #{name} missing locals: #{missing.join(', ')}" unless missing.empty?
      "Hamster::CompiledViews.render(#{name.dump}, context, #{locals})"
    end

    def rewrite_content_for(code, path, line)
      match = code.match(/\Acontent_for\s*(?:\(\s*)?:(\w+)\s*,\s*(.+?)\s*\)?\z/m)
      raise View::Error, "#{path}:#{line}: content_for requires a literal slot and value" unless match
      "context.content_for(#{match[1].dump}, #{match[2]})"
    end

    def yield_name(code, path, line)
      return nil unless code.match?(/\Ayield\b/)
      return "body" if code == "yield"
      match = code.match(/\Ayield\s*(?:\(\s*)?:(\w+)\s*\)?\z/)
      raise View::Error, "#{path}:#{line}: yield requires a literal slot name" unless match
      match[1]
    end

    def validate_position!(context, path, line)
      raise View::Error, "#{path}:#{line}: dynamic script or style content" if context == :script
      raise View::Error, "#{path}:#{line}: expression must be in text or a quoted attribute" if context == :tag
      if context.is_a?(String) && (context.start_with?("on") || %w[style srcdoc].include?(context))
        raise View::Error, "#{path}:#{line}: dynamic event or style attribute"
      end
    end

    def check_ruby!(code, path, line)
      raise View::Error, "#{path}:#{line}: invalid Ruby expression" unless Ripper.sexp(code)
    end

    def check_ruby_fragment!(code, path, line)
      return if code.match?(/\A(?:if|unless|elsif|else)\b/) || code.match?(/\A[a-z_][\w.]*\.each\s+do(?:\s*\|[^|]+\|)?\s*\z/)
      raise View::Error, "#{path}:#{line}: unsupported ERB code"
    end

    def detect_cycles!(deps, paths)
      visited = {}
      visit = lambda do |name, stack|
        return if visited[name]
        deps.fetch(name).each do |child, line|
          if stack.include?(child) || child == name
            raise View::Error, "#{paths[name]}:#{line}: partial dependency cycle: #{(stack + [name, child]).join(' -> ')}"
          end
          visit.call(child, stack + [name])
        end
        visited[name] = true
      end
      deps.keys.each { |name| visit.call(name, []) }
    end

    def unresolved_identifier(node)
      return nil unless node.is_a?(Array)
      if node[0] == :vcall && node[1].is_a?(Array) && node[1][0] == :@ident
        return node[1][1]
      end
      node.each do |child|
        result = unresolved_identifier(child)
        return result if result
      end
      nil
    end
  end
end
