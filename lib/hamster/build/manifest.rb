# frozen_string_literal: true

require "ripper"
require "fileutils"
require_relative "../web"
require_relative "view_compiler"
require_relative "query_accessors"
require_relative "callbacks"
require_relative "assets"

module Hamster
  module Build
    module Manifest
      module_function

      def outputs(root)
        paths = Dir.glob("{app,db}/**/*.rb", base: root).reject { |path| path.start_with?("db/migrations/") }.sort_by do |path|
          priority = path.start_with?("db/") ? 0 : path.start_with?("app/models/") ? 1 : 2
          priority = 2 if path.start_with?("app/concerns/")
          priority = 3 if path.start_with?("app/routes/")
          priority = 4 if path == "app/routes/mappings.rb"
          [priority, path]
        end
        paths = Callbacks.order(paths.to_h { |path| [path, File.read(File.join(root, path))] })
        sources = {}
        Dir.glob("{app/routes,app/views}/**/*.html.erb", base: root).sort.each do |path|
          name = path.sub(%r{\Aapp/(?:routes|views)/}, "").sub(%r{/view\.html\.erb\z}, "").delete_suffix(".html.erb")
          raise View::Error, "duplicate template #{name}" if sources.key?(name)
          sources[name] = {path: path, source: File.read(File.join(root, path))}
        end
        lines = paths.map { |path| %(require_relative "../#{path.delete_suffix('.rb')}") }
        paths.each { |path| lines.concat(QueryAccessors.lines(File.read(File.join(root, path)))) }
        paths.each { |path| lines.concat(QueryAccessors.lines(File.read(File.join(root, path)), declaration: "column", writers: true)) }
        lines.concat(QueryAccessors.schema_guards(paths.map { |path| File.read(File.join(root, path)) }))
        lines << 'require_relative "callback_registry"'
        lines << 'require_relative "view_registry"'
        lines << 'require_relative "asset_registry"'
        assets = Assets.outputs(root)
        sources.each_value do |template|
          template[:source].scan(/Hamster::Assets.path\(["']([^"']+)["']\)/).flatten.each do |name|
            raise View::Error, "#{template[:path]}:1: missing asset #{name}" unless assets["public/assets/manifest.json"].include?(name.to_json)
          end
        end
        {
          "config/manifest.rb" => "# frozen_string_literal: true\n# Generated by hamster manifest.\n" + lines.join("\n") + "\n",
          "config/view_registry.rb" => ViewCompiler.compile(sources),
          "config/callback_registry.rb" => Callbacks.compile(paths.map { |path| File.read(File.join(root, path)) })
        }.merge(assets)
      end

      def generate(root)
        outputs(root).each do |path, content|
          FileUtils.mkdir_p(File.dirname(File.join(root, path)))
          File.binwrite(File.join(root, path), content)
        end
      end

      def check(root, expected: nil)
        issues = (expected || outputs(root)).filter_map do |path, expected|
          actual = File.file?(File.join(root, path)) ? File.binread(File.join(root, path)) : nil
          "#{path} is missing or stale; run bin/hamster manifest" unless actual == expected.b
        end
        Dir.glob("{app,db}/**/*.rb", base: root).each do |path|
          Ripper.lex(File.read(File.join(root, path))).each do |position, type, token, _|
            issues << "#{path}:#{position[0]}: load files through the manifest" if type == :on_ident && token == "require_relative"
          end
        end
        issues
      end
    end
  end
end
